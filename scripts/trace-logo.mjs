import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { promisify } from "node:util";
import potrace from "potrace";
import sharp from "sharp";
import { ASSETS, PUBLIC, ROOT } from "./asset-map.mjs";

const SRC = path.join(ASSETS, "logo", "logo_1.jpeg");
const BRAND_RED = "#ED1C24";
const CREAM = "#F9F4F1";
const MARK_ONLY_HEIGHT = 0.82;

const trace = promisify(potrace.trace);

const trimmed = await sharp(SRC)
  .flatten({ background: "#ffffff" })
  .trim({ threshold: 40 })
  .toBuffer({ resolveWithObject: true });
const { width, height } = trimmed.info;
const pngForTrace = await sharp(trimmed.data).grayscale().png().toBuffer();

const svg = await trace(pngForTrace, {
  threshold: 160,
  turdSize: 8,
  optTolerance: 0.25,
  color: "currentColor",
  background: "transparent",
});

const d = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]).join(" ");
if (!d) throw new Error("potrace returned no path data");

const markHeight = Math.round(height * MARK_ONLY_HEIGHT);

const tsDest = path.join(ROOT, "src", "components", "brand", "logo-size.generated.ts");
mkdirSync(path.dirname(tsDest), { recursive: true });
writeFileSync(
  tsDest,
  `// Generated by scripts/trace-logo.mjs from assets/logo/logo_1.jpeg — do not edit by hand.\n` +
    `export const LOGO_WIDTH = ${width};\nexport const LOGO_HEIGHT = ${height};\nexport const LOGO_MARK_HEIGHT = ${markHeight};\n`,
);

const brandDir = path.join(PUBLIC, "brand");
mkdirSync(brandDir, { recursive: true });
const svgFile = (fill, h) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${h}"><path fill="${fill}" fill-rule="evenodd" d="${d}"/></svg>\n`;
writeFileSync(path.join(brandDir, "logo-red.svg"), svgFile(BRAND_RED, height));
writeFileSync(path.join(brandDir, "logo-cream.svg"), svgFile(CREAM, height));
writeFileSync(path.join(brandDir, "logo-mark-cream.svg"), svgFile(CREAM, markHeight));

const markSvg = Buffer.from(
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${markHeight}" width="${width}" height="${markHeight}"><path fill="${BRAND_RED}" fill-rule="evenodd" d="${d}"/></svg>`,
);
for (const [file, size] of [
  ["icon.png", 512],
  ["apple-icon.png", 180],
]) {
  const inner = Math.round(size * 0.8);
  const mark = await sharp(markSvg, { density: 300 })
    .resize({ width: inner, height: inner, fit: "inside" })
    .png()
    .toBuffer();
  await sharp({ create: { width: size, height: size, channels: 4, background: CREAM } })
    .composite([{ input: mark, gravity: "center" }])
    .png()
    .toFile(path.join(ROOT, "src", "app", file));
}

console.log(
  `logo ${width}x${height}, path ${(d.length / 1024).toFixed(1)} KB → public/brand/logo-*.svg, ${path.relative(ROOT, tsDest)}, src/app/icon.png`,
);
